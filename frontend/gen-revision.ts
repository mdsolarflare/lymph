/**
 * gen-revision.ts — build-time cache revision map generator.
 *
 * Hashes every precached shell file with SHA-256 (crypto.subtle — no deps)
 * and emits `dist/cache-manifest.js`:
 *
 *   self.CACHE_MANIFEST = { buildId, files };
 *
 * `buildId` = SHA-256 over the sorted (path, hash) list, so any content
 * change to any shell file produces a new buildId → new cache name →
 * service-worker update. This replaces filename hashing, which the
 * deno bundle build deliberately avoids.
 *
 * ALSO stamps the buildId into dist/sw.js. Chromium byte-compares only the
 * MAIN sw script on its update check; a changed importScripts'd manifest
 * alone never triggers an update — so without this stamp the shell would be
 * pinned to the first build the browser ever saw.
 *
 * sw.js / cache-manifest.js are deliberately NOT in SHELL_FILES: SW scripts
 * are fetched outside the SW's own fetch handler.
 *
 * Run from frontend/: part of `deno task build` (needs dist/ fully staged).
 */

const SHELL_FILES = [
  "index.html",
  "manifest.webmanifest",
  "favicon.svg",
  "icons/icon-192.png",
  "icons/icon-512.png",
  "icons/icon-512-maskable.png",
  "icons/apple-touch-icon.png",
  "app.js",
  "styles.css",
  "lymph_core_bg.wasm",
];

const DIST = new URL("./dist/", import.meta.url);

async function sha256(bytes: Uint8Array): Promise<string> {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    bytes as unknown as BufferSource,
  );
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

// URL→Windows-path conversion (Deno cannot read MSYS paths; .pathname
// yields /C:/... on Windows which stat rejects as absolute-rooted).
function toFsPath(url: URL): string {
  const m = url.pathname.match(/^\/([A-Za-z]:\/.*)/);
  return m?.[1] ?? url.pathname;
}

const files: Array<{ path: string; hash: string }> = [];
for (const rel of SHELL_FILES) {
  const bytes = await Deno.readFile(toFsPath(new URL(rel, DIST)));
  const hash = await sha256(bytes);
  files.push({ path: rel, hash });
}

// buildId: hash of the whole manifest so one id covers every file.
const buildId = await sha256(
  new TextEncoder().encode(
    files.map((f) => `${f.path}:${f.hash}`).join("\n"),
  ),
);

const manifest = {
  buildId,
  files: files.map((f) => f.path),
};

const out = `// AUTO-GENERATED by gen-revision.ts — do not edit.\n` +
  `// Any shell change rewrites buildId, which renames the SW cache and\n` +
  `// forces a service-worker update (see sw.js).\n` +
  `self.CACHE_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;

await Deno.writeTextFile(
  toFsPath(new URL("cache-manifest.js", DIST)),
  out,
);

// Stamp the buildId into the SW main script (the staged dist/ copy — the
// frontend/sw.js source keeps the zero placeholder for the next build).
const swPath = toFsPath(new URL("sw.js", DIST));
const swSrc = await Deno.readTextFile(swPath);
// Whitespace-tolerant: deno fmt may wrap the line after `=` (string literal
// on the following line), so match comment + declaration across both shapes.
const STAMP_RE =
  /^(\/\/ AUTO-STAMPED by gen-revision\.ts — do not edit by hand\.\r?\nconst BUILD_ID =\r?\n?\s*)"?[0-9a-f]{64}"?(;\r?\n)$/m;
if (!STAMP_RE.test(swSrc)) {
  throw new Error(
    `sw.js is missing the BUILD_ID stamp placeholder — re-add the AUTO-STAMPED const BUILD_ID line`,
  );
}
const stamped = swSrc.replace(
  STAMP_RE,
  `$1"${buildId}"$2`,
);
await Deno.writeTextFile(swPath, stamped);

console.log(
  `cache-manifest.js: buildId=${
    buildId.slice(0, 12)
  }… (${files.length} files) — sw.js stamped`,
);
